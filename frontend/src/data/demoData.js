export function getDemoHotspotById(zoneId) {
  for (const city of Object.keys(demoHotspots)) {
    const found = demoHotspots[city].find((h) => h.zone_id === zoneId);
    if (found) return found;
  }
  return null;
}

export function buildDemoReport(zone) {
  if (!zone) return null;
  return {
    zone_summary: {
      zone_id: zone.zone_id,
      zone_name: zone.zone_name,
      city: zone.city,
      latitude: zone.latitude,
      longitude: zone.longitude,
    },
    heat_condition: {
      heat_risk_score: zone.heat_risk_score,
      hotspot_category: zone.hotspot_category,
      lst_temperature: zone.lst_temperature,
      air_temperature: zone.air_temperature,
      humidity: zone.humidity,
      wind_speed: zone.wind_speed,
    },
    main_causes: zone.main_drivers,
    recommended_actions: zone.recommended_action,
    expected_temperature_reduction: zone.expected_temp_reduction,
    priority_level: zone.priority_level,
    implementation_suggestions: [
      "Plant native shade trees along streets and in open plots.",
      "Roll out cool-roof coatings on public and commercial buildings.",
      "Add reflective, high-albedo materials to dark pavements.",
      "Monitor heat trends seasonally and review progress.",
    ],
    generated_at: new Date().toISOString(),
  };
}

